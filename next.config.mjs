/**
 * Next.js 14 config for lap-webapp (deploys at app.lap.com).
 * Strict-ish CSP + standard hardening headers. Env wiring falls back
 * to the production API origin when NEXT_PUBLIC_API_URL is unset.
 */

const apiOrigin = process.env.NEXT_PUBLIC_API_URL ?? "https://api.lap.com";

const csp = [
  "default-src 'self'",
  // Next.js injects inline bootstrap scripts. Nonces would tighten this
  // further but require a middleware layer — deferred until auth lands.
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: blob:",
  `connect-src 'self' ${apiOrigin}`,
  "worker-src 'self' blob:",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "upgrade-insecure-requests",
].join("; ");

/** @type {import('next').NextConfig} */
const nextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
          {
            key: "Strict-Transport-Security",
            value: "max-age=31536000; includeSubDomains",
          },
          { key: "Content-Security-Policy", value: csp },
        ],
      },
    ];
  },
};

export default nextConfig;
